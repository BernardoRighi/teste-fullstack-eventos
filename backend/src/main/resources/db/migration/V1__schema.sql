CREATE TABLE instituicao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(150) NOT NULL,
 tipo VARCHAR(30) NOT NULL,
 CONSTRAINT ck_instituicao_tipo CHECK (tipo IN ('CONFEDERACAO','SINGULAR','CENTRAL','COOPERATIVA'))
);
CREATE TABLE evento (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 instituicao_id BIGINT NOT NULL REFERENCES instituicao(id),
 nome VARCHAR(150) NOT NULL,
 data_inicial DATE NOT NULL,
 data_final DATE NOT NULL,
 ativo BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT ck_evento_periodo CHECK (data_final >= data_inicial)
);
CREATE INDEX idx_evento_instituicao ON evento(instituicao_id);
CREATE INDEX idx_evento_vigencia ON evento(data_inicial, data_final);
